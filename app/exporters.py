import os
import uuid
from fpdf import FPDF

EXPORTS_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "static", "exports")
os.makedirs(EXPORTS_DIR, exist_ok=True)

class ComicPDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 16)
        self.set_text_color(245, 197, 24)
        self.set_fill_color(20, 20, 35)
        self.cell(0, 12, "COMICCRAFT - AI STORYBOOK", border=0, ln=1, align="C", fill=True)
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 9)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by ComicCraft AI", align="C")

def sanitize_text(text: str) -> str:
    """Replaces non-latin1 characters to prevent fpdf encoding errors."""
    if not text:
        return ""
    # Map common unicode quotes and symbols to ASCII
    replacements = {
        '“': '"', '”': '"', '‘': "'", '’': "'", '—': '-', '–': '-',
        '⚡': '', '✨': '', '💥': '', '🎨': ''
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return text.encode('latin-1', 'replace').decode('latin-1')

def save_pdf(layout: list) -> str:
    """
    Generates a PDF document from the comic layout list using fpdf2.
    Saves PDF to static/exports/ and returns relative path '/static/exports/comic_filename.pdf'.
    """
    pdf = ComicPDF(orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    
    base_dir = os.path.dirname(os.path.dirname(__file__))

    for item in layout:
        panel_num = item.get("panel", 1)
        title = sanitize_text(item.get("title", f"Panel {panel_num}"))
        caption = sanitize_text(item.get("caption", ""))
        narration = sanitize_text(item.get("narration", ""))
        dialogue = sanitize_text(item.get("dialogue", ""))
        image_path_rel = item.get("image_path", "").lstrip("/")

        # Check space left on page, add page if needed
        if pdf.get_y() > 200:
            pdf.add_page()

        # Panel Section Container Header
        pdf.set_font("Helvetica", "B", 13)
        pdf.set_text_color(30, 40, 70)
        pdf.set_fill_color(230, 235, 245)
        pdf.cell(0, 8, f" PANEL {panel_num}: {title}", ln=True, fill=True)
        pdf.ln(3)

        start_y = pdf.get_y()

        # Embed Image if present
        full_img_path = os.path.join(base_dir, image_path_rel) if image_path_rel else ""
        img_w = 65
        img_h = 65

        if full_img_path and os.path.exists(full_img_path):
            try:
                pdf.image(full_img_path, x=15, y=start_y, w=img_w, h=img_h)
            except Exception as img_err:
                print(f"[Exporters] Warning: Could not embed image {full_img_path}: {img_err}")
                pdf.rect(15, start_y, img_w, img_h)
                pdf.set_xy(15, start_y + 30)
                pdf.set_font("Helvetica", "I", 9)
                pdf.cell(img_w, 10, "[Image Error]", align="C")
        else:
            pdf.rect(15, start_y, img_w, img_h)
            pdf.set_xy(15, start_y + 30)
            pdf.set_font("Helvetica", "I", 9)
            pdf.cell(img_w, 10, "[No Image]", align="C")

        # Text Content alongside Image
        text_x = 85
        text_w = 110
        pdf.set_xy(text_x, start_y)

        if caption:
            pdf.set_font("Helvetica", "B", 10)
            pdf.set_text_color(100, 80, 20)
            pdf.multi_cell(text_w, 5, f"CAPTION: {caption}")
            pdf.ln(2)
            pdf.set_x(text_x)

        if narration:
            pdf.set_font("Helvetica", "I", 10)
            pdf.set_text_color(40, 40, 40)
            pdf.multi_cell(text_w, 5, f"NARRATION: {narration}")
            pdf.ln(2)
            pdf.set_x(text_x)

        if dialogue:
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(10, 80, 160)
            pdf.multi_cell(text_w, 5, f"DIALOGUE:\n{dialogue}")

        # Ensure next element starts below the panel height
        end_y = max(start_y + img_h + 5, pdf.get_y() + 5)
        pdf.set_y(end_y)
        
        # Horizontal divider
        pdf.set_draw_color(200, 200, 210)
        pdf.line(15, end_y, 195, end_y)
        pdf.ln(4)

    filename = f"comic_{uuid.uuid4().hex[:10]}.pdf"
    output_path = os.path.join(EXPORTS_DIR, filename)
    pdf.output(output_path)

    return f"/static/exports/{filename}"
